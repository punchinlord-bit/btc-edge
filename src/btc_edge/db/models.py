"""SQLAlchemy 2.0 / SQLite schema for BTC-Edge.

Persists market windows, signals, orders, fills, settlements, and per-rule
grade metrics. All timestamps are stored as unix epoch seconds (float) for
timezone-free math.
"""

from __future__ import annotations

import time
from datetime import UTC, datetime

from sqlalchemy import (
    Boolean,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


def utcnow_ts() -> float:
    return datetime.now(UTC).timestamp()


class Base(DeclarativeBase):
    pass


class Window(Base):
    """A prediction-market settlement window (Kalshi KXBTC15M or Polymarket)."""

    __tablename__ = "windows"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    venue: Mapped[str] = mapped_column(String(16), index=True)  # kalshi | polymarket
    market_slug: Mapped[str] = mapped_column(String(128), index=True)
    timeframe_seconds: Mapped[int] = mapped_column(Integer)  # 300 / 600 / 900
    window_ts: Mapped[int] = mapped_column(Integer, index=True)  # window open unix ts
    window_open_price: Mapped[float] = mapped_column(Float)
    settle_price: Mapped[float] = mapped_column(Float, default=0.0)
    resolved: Mapped[bool] = mapped_column(Boolean, default=False)
    outcome: Mapped[str] = mapped_column(String(16), default="unresolved")  # up|down
    result: Mapped[float] = mapped_column(Float, default=0.0)  # 1.0 win / 0.0 loss
    created_at: Mapped[float] = mapped_column(Float, default=utcnow_ts)
    settled_at: Mapped[float | None] = mapped_column(Float, nullable=True)

    __table_args__ = (
        Index("ix_windows_venue_slug", "venue", "market_slug", unique=True),
    )


class Signal(Base):
    """A strategy-generated entry signal with full feature/rule snapshot."""

    __tablename__ = "signals"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    window_id: Mapped[int] = mapped_column(ForeignKey("windows.id"), index=True)
    strategy: Mapped[str] = mapped_column(String(32), index=True)
    side: Mapped[str] = mapped_column(String(8))  # up | down
    contract_price: Mapped[float] = mapped_column(Float)
    prob_estimate: Mapped[float] = mapped_column(Float)
    window_delta_pct: Mapped[float] = mapped_column(Float, default=0.0)
    option_implied_prob: Mapped[float] = mapped_column(Float, default=0.0)
    book_imbalance: Mapped[float] = mapped_column(Float, default=0.0)
    micro_acceleration: Mapped[float] = mapped_column(Float, default=0.0)
    regime: Mapped[str] = mapped_column(String(16), default="UNKNOWN")
    time_remaining: Mapped[float] = mapped_column(Float, default=0.0)
    rule_snapshot_json: Mapped[str] = mapped_column(Text, default="{}")
    ev_estimate: Mapped[float] = mapped_column(Float, default=0.0)
    timestamp: Mapped[float] = mapped_column(Float, default=utcnow_ts, index=True)

    window: Mapped[Window] = relationship()


class Order(Base):
    """An order generated by the execution router."""

    __tablename__ = "orders"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    signal_id: Mapped[int | None] = mapped_column(ForeignKey("signals.id"), nullable=True)
    venue: Mapped[str] = mapped_column(String(16))
    side: Mapped[str] = mapped_column(String(8))
    price: Mapped[float] = mapped_column(Float)
    size: Mapped[float] = mapped_column(Float)
    order_type: Mapped[str] = mapped_column(String(16))  # maker | taker
    idempotency_key: Mapped[str] = mapped_column(String(64), default="", index=True)
    status: Mapped[str] = mapped_column(String(16), default="open")  # open|filled|canceled
    created_at: Mapped[float] = mapped_column(Float, default=utcnow_ts)


class Fill(Base):
    """A realized fill with exact fees and slippage."""

    __tablename__ = "fills"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    order_id: Mapped[int | None] = mapped_column(ForeignKey("orders.id"), nullable=True)
    venue: Mapped[str] = mapped_column(String(16))
    side: Mapped[str] = mapped_column(String(8))
    price: Mapped[float] = mapped_column(Float)
    size: Mapped[float] = mapped_column(Float)
    fee: Mapped[float] = mapped_column(Float, default=0.0)
    slippage: Mapped[float] = mapped_column(Float, default=0.0)
    is_maker: Mapped[bool] = mapped_column(Boolean, default=False)
    timestamp: Mapped[float] = mapped_column(Float, default=utcnow_ts, index=True)


class Settlement(Base):
    """Per-strategy PnL settlement on a resolved window."""

    __tablename__ = "settlements"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    window_id: Mapped[int] = mapped_column(ForeignKey("windows.id"), index=True)
    strategy: Mapped[str] = mapped_column(String(32))
    pnl: Mapped[float] = mapped_column(Float, default=0.0)
    fee_total: Mapped[float] = mapped_column(Float, default=0.0)
    realized_net_ev: Mapped[float] = mapped_column(Float, default=0.0)
    win: Mapped[bool] = mapped_column(Boolean, default=False)
    brier_term: Mapped[float] = mapped_column(Float, default=0.0)
    timestamp: Mapped[float] = mapped_column(Float, default=utcnow_ts)


class RuleMetric(Base):
    """Per-strategy/per-rule trailing performance grade for the nightly grader."""

    __tablename__ = "rule_metrics"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    strategy: Mapped[str] = mapped_column(String(32), index=True)
    rule_id: Mapped[str] = mapped_column(String(64), index=True)
    window_id: Mapped[int] = mapped_column(ForeignKey("windows.id"))
    evaluation_json: Mapped[str] = mapped_column(Text, default="{}")
    net_ev: Mapped[float] = mapped_column(Float, default=0.0)
    win: Mapped[bool] = mapped_column(Boolean, default=False)
    trailing_status: Mapped[str] = mapped_column(String(32), default="ACTIVE")
    timestamp: Mapped[float] = mapped_column(Float, default=utcnow_ts)


class NewsArticle(Base):
    """A fetched news headline with its sentiment score."""

    __tablename__ = "news_articles"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    source: Mapped[str] = mapped_column(String(64), index=True)
    title: Mapped[str] = mapped_column(Text)
    summary: Mapped[str] = mapped_column(Text, default="")
    url: Mapped[str] = mapped_column(Text, default="")
    published_ts: Mapped[float] = mapped_column(Float, default=0.0)
    relevance: Mapped[float] = mapped_column(Float, default=0.0)
    sentiment: Mapped[float] = mapped_column(Float, default=0.0)
    confidence: Mapped[float] = mapped_column(Float, default=0.0)
    timestamp: Mapped[float] = mapped_column(Float, default=utcnow_ts, index=True)


class NewsSourceMetric(Base):
    """Per-source predictive accuracy for the self-healing filter."""

    __tablename__ = "news_source_metrics"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    source: Mapped[str] = mapped_column(String(64), index=True, unique=True)
    signals: Mapped[int] = mapped_column(Integer, default=0)
    correct: Mapped[int] = mapped_column(Integer, default=0)
    accuracy: Mapped[float] = mapped_column(Float, default=0.5)
    status: Mapped[str] = mapped_column(String(16), default="ACTIVE")
    weight: Mapped[float] = mapped_column(Float, default=1.0)
    updated_at: Mapped[float] = mapped_column(Float, default=utcnow_ts)


class StrategyVersion(Base):
    """Versioned strategy registry (Champion vs. Challenger promotion gate)."""

    __tablename__ = "strategy_versions"

    version_id: Mapped[str] = mapped_column(String(64), primary_key=True)
    market_key: Mapped[str] = mapped_column(String(32), default="btc_15m", index=True)
    parent_version_id: Mapped[str | None] = mapped_column(String(64), nullable=True)
    status: Mapped[str] = mapped_column(String(16), default="CHALLENGER", index=True)
    config_json: Mapped[str] = mapped_column(Text, default="{}")
    metrics_json: Mapped[str] = mapped_column(Text, default="{}")
    gate_checks_json: Mapped[str] = mapped_column(Text, default="{}")
    created_by: Mapped[str] = mapped_column(String(32), default="learning_loop")
    evaluated_at: Mapped[float] = mapped_column(Float, default=utcnow_ts)
    promoted_at: Mapped[float | None] = mapped_column(Float, nullable=True)

    __table_args__ = (
        Index("ix_strategy_versions_active_champ", "market_key", "status"),
    )


class Btc15mWindowEvaluation(Base):
    """15-minute BTC window evaluation ledger (OOS samples for the gate)."""

    __tablename__ = "btc_15m_window_evaluations"

    window_start_sec: Mapped[int] = mapped_column(Integer, primary_key=True)
    strike_price: Mapped[float] = mapped_column(Float)
    close_price: Mapped[float] = mapped_column(Float)
    outcome: Mapped[int] = mapped_column(Integer)  # 0 = down, 1 = up
    regime: Mapped[str] = mapped_column(String(8))  # chop | trend | spike
    features_json: Mapped[str] = mapped_column(Text, default="{}")
    market_ask_up: Mapped[float] = mapped_column(Float, default=0.55)
    market_ask_down: Mapped[float] = mapped_column(Float, default=0.55)
    fee_rate: Mapped[float] = mapped_column(Float, default=0.015)
    champion_version_id: Mapped[str | None] = mapped_column(String(64), nullable=True)
    champion_prob_up: Mapped[float | None] = mapped_column(Float, nullable=True)
    created_at: Mapped[float] = mapped_column(Float, default=utcnow_ts)


# Re-export helpers
def current_ts() -> float:
    return time.time()
